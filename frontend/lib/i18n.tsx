type MessageKey = keyof (typeof messages)["ZH"];

interface I18nContextValue {
  language: UiLanguage;
  setLanguage: (language: UiLanguage) => void;
  t: (key: MessageKey) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [storedLanguage, setStoredLanguage] = useStoredValue<UiLanguage>(
    "karisanki-language",
    typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("zh") ? "ZH" : "EN",
  );
  const language = storedLanguage === "ZH" || storedLanguage === "EN" ? storedLanguage : "ZH";
  const setLanguage = (next: UiLanguage) => setStoredLanguage(next);

  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = language === "ZH" ? "zh-CN" : "en";
    }
  }, [language]);

  const value: I18nContextValue = {
    language,
    setLanguage,
    t: (key) => messages[language][key],
  };

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used inside I18nProvider");
  }
  return context;
}
